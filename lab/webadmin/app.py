"""Fake web admin panel (honeypot). Never authenticates anyone; logs every request as JSON lines."""
import json
import os
import time
from datetime import datetime, timezone
from pathlib import Path

from flask import Flask, Response, redirect, render_template, request

LOG_PATH = os.environ.get("WEB_LOG", "/logs/web.json")
SERVER_HEADER = "Apache/2.4.57 (Debian)"  # what scanners like nikto will read

app = Flask(__name__)


def log_event(status):
    event = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "eventid": "web.request",
        "src_ip": request.remote_addr,  # Docker gateway, see README
        "method": request.method,
        "path": request.path,
        "query": request.query_string.decode("utf-8", "replace"),
        "status": status,
        "user_agent": request.headers.get("User-Agent", ""),
        "host": request.headers.get("Host", ""),
    }
    if request.path == "/login" and request.method == "POST":
        event["eventid"] = "web.login"
        event["username"] = request.form.get("username", "")
        event["password"] = request.form.get("password", "")
    try:
        with open(LOG_PATH, "a") as f:
            f.write(json.dumps(event) + "\n")
    except OSError:
        pass  # never break the response because logging failed


@app.after_request
def finish(resp):
    resp.headers["Server"] = SERVER_HEADER
    log_event(resp.status_code)
    return resp


@app.route("/")
def index():
    return redirect("/login")


@app.route("/login", methods=["GET", "POST"])
def login():
    if request.method == "POST":
        time.sleep(0.5)  # small delay, like a real auth backend
        return render_template("login.html", error="Invalid username or password."), 401
    return render_template("login.html", error=None)


@app.route("/robots.txt")
def robots():
    return Response("User-agent: *\nDisallow: /admin/\nDisallow: /backup/\n", mimetype="text/plain")


@app.route("/admin/")
@app.route("/admin")
def admin():
    return redirect("/login")


LURE_DIR = Path(__file__).parent / "lures" / "backup"   # generated by lab/lures/render.py
# What the directory listing shows: (name, last modified, size, downloadable). Only the first two files exist.
BACKUP_LISTING = [("README.txt", "2026-09-12 09:41", "152", True), ("config.bak", "2026-09-12 09:40", "232", True),
                  ("db_export_2026-09-30.sql.gz", "2026-09-30 02:10", "14M", False)]


@app.route("/backup/")
@app.route("/backup")
def backup_index():
    """A forgotten directory listing in the web root: the lure. Looks like Apache's autoindex."""
    rows = "".join(f'<tr><td valign="top"><a href="{n}">{n}</a></td><td align="right">{d}  </td><td align="right">{z}</td></tr>\n'
                   for n, d, z, _ in BACKUP_LISTING)
    host, _, port = request.host.partition(":")
    page = ('<!DOCTYPE HTML PUBLIC "-//W3C//DTD HTML 3.2 Final//EN">\n<html>\n <head>\n  <title>Index of /backup</title>\n </head>\n <body>\n'
            '<h1>Index of /backup</h1>\n  <table>\n   <tr><th>Name</th><th>Last modified</th><th>Size</th></tr>\n'
            f'<tr><th colspan="3"><hr></th></tr>\n{rows}<tr><th colspan="3"><hr></th></tr>\n</table>\n'
            f'<address>{SERVER_HEADER} Server at {host} Port {port or "80"}</address>\n</body></html>\n')
    return Response(page, mimetype="text/html")


@app.route("/backup/<path:name>")
def backup_file(name):
    listed = {n: ok for n, _, _, ok in BACKUP_LISTING}
    if name not in listed:
        return Response("Not Found", status=404, mimetype="text/plain")
    f = LURE_DIR / name
    if not listed[name] or not f.is_file():        # the big export is listed but not downloadable
        return Response("Forbidden", status=403, mimetype="text/plain")
    return Response(f.read_text(encoding="utf-8"), mimetype="text/plain")


@app.route("/server-status")
def forbidden():
    return Response("Forbidden", status=403, mimetype="text/plain")
